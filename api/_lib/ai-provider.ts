import { OpenAI } from 'openai';
import { GoogleGenAI } from '@google/genai';
import { AppState } from '../../src/db/concurrencyEngine.ts';
import { formatINR, calculateCashForecast, getEligibleItc } from '../../src/utils/accounting.ts';
import { getIntegrations } from './db.ts';

export interface AiQueryResult {
  answer: string;
  basis: string;
  sources: string[];
  providerUsed: 'openai' | 'gemini' | 'deterministic';
  modelUsed?: string;
}

export function buildAccountingContext(state: AppState): string {
  const openReceivables = state.receivables.filter(r => r.status !== 'Settled');
  const totalReceivables = openReceivables.reduce((acc, r) => acc + r.amount, 0);
  const overdueReceivables = openReceivables.filter(r => r.agingDays > 0);
  const overdueTotal = overdueReceivables.reduce((acc, r) => acc + r.amount, 0);

  const openPayables = state.payables.filter(p => p.status !== 'Settled');
  const totalPayables = openPayables.reduce((acc, p) => acc + p.amount, 0);

  const eligibleItc = getEligibleItc(state.gstRows);
  const netGstLiability = Math.max(0, state.salesTaxOutput - eligibleItc);

  const forecast = calculateCashForecast(state.cashBalance, state.receivables, state.payables);
  const baseLowPoint = Math.min(...forecast.map(d => d.baseScenarioCash));

  return `
Company Legal Name: ${state.company.legalName}
GSTIN: ${state.company.gstin}
Current Cash/Bank Balance: ${formatINR(state.cashBalance)}
Total Open Receivables: ${formatINR(totalReceivables)} (Overdue: ${formatINR(overdueTotal)} across ${overdueReceivables.length} customer invoices)
Top Overdue Customers:
${overdueReceivables.slice(0, 4).map(r => ` - ${r.customer}: ${formatINR(r.amount)} (due ${r.dueDate}, ${r.agingDays} days late)`).join('\n') || 'None'}
Total Open Supplier Payables: ${formatINR(totalPayables)} across ${openPayables.length} bills
Net GST Liability for Month: ${formatINR(netGstLiability)} (Output Tax: ${formatINR(state.salesTaxOutput)}, ITC Available: ${formatINR(eligibleItc)})
30-Day Cash Forecast Low Point: ${formatINR(baseLowPoint)}
`.trim();
}

export async function askMultiAi(
  question: string,
  state: AppState,
  options?: {
    provider?: 'gemini' | 'openai';
    apiKey?: string;
    model?: string;
  }
): Promise<AiQueryResult> {
  const integrations = await getIntegrations();
  const provider = options?.provider || integrations.activeAiProvider || 'gemini';
  const context = buildAccountingContext(state);

  const systemInstruction = `You are "AI Munim", an expert Indian Chartered Accountant and CFO copilot.
You are assisting the management of ${state.company.legalName}.
Use ONLY the verified accounting figures provided in the context below.
Provide a clear, executive-level financial answer with direct figures in Indian Rupees (₹), followed by actionable recommendations.
Keep answers concise, professional, and audit-compliant.

Accounting Context:
${context}`;

  // 1. Try OpenAI if selected
  if (provider === 'openai') {
    const apiKey = options?.apiKey || integrations.openaiApiKey || process.env.OPENAI_API_KEY;
    const model = options?.model || integrations.openaiModel || 'gpt-4o-mini';

    if (apiKey) {
      try {
        const client = new OpenAI({ apiKey });
        const completion = await client.chat.completions.create({
          model,
          messages: [
            { role: 'system', content: systemInstruction },
            { role: 'user', content: question }
          ],
          temperature: 0.2
        });

        const reply = completion.choices[0]?.message?.content || '';
        if (reply) {
          return {
            answer: reply,
            basis: `Generated by OpenAI (${model}) grounded in real-time general ledger data.`,
            sources: ['NeonDB Ledgers', 'Accounts Receivable Register', 'Cash Flow Engine', 'OpenAI'],
            providerUsed: 'openai',
            modelUsed: model
          };
        }
      } catch (err: any) {
        console.warn('[OpenAI Generation Failed, attempting fallback]', err?.message);
      }
    }
  }

  // 2. Try Gemini if selected or as fallback
  const geminiKey = options?.apiKey || integrations.geminiApiKey || process.env.GEMINI_API_KEY;
  const geminiModel = options?.model || integrations.geminiModel || 'gemini-2.5-flash';

  if (geminiKey) {
    try {
      const ai = new GoogleGenAI({ apiKey: geminiKey });
      const response = await ai.models.generateContent({
        model: geminiModel,
        contents: `${systemInstruction}\n\nUser Question: ${question}`
      });

      const reply = response.text || '';
      if (reply) {
        return {
          answer: reply,
          basis: `Generated by Google Gemini (${geminiModel}) grounded in real-time general ledger data.`,
          sources: ['NeonDB Ledgers', 'GST Portal (GSTR-2B)', 'Cash Flow Engine', 'Gemini'],
          providerUsed: 'gemini',
          modelUsed: geminiModel
        };
      }
    } catch (err: any) {
      console.warn('[Gemini Generation Failed, falling back to deterministic]', err?.message);
    }
  }

  // 3. Deterministic Munim fallback
  const q = question.toLowerCase();
  let answer = '';
  let basis = 'Deterministic AI Munim rule-based calculation layer.';
  const sources = ['General Ledger', 'Audit Trail'];

  if (q.includes('overdue') || q.includes('customer') || q.includes('collection')) {
    const overdue = state.receivables.filter(r => r.status !== 'Settled' && r.agingDays > 0);
    const total = overdue.reduce((sum, r) => sum + r.amount, 0);
    answer = `Currently, ₹${total.toLocaleString('en-IN')} is overdue across ${overdue.length} customer invoices. Top debtor: ${overdue[0]?.customer || 'None'} with ₹${(overdue[0]?.amount || 0).toLocaleString('en-IN')}.`;
    basis = 'Aggregated from real-time Accounts Receivable ledger filtered by agingDays > 0.';
    sources.push('Accounts Receivable Control');
  } else if (q.includes('cash') || q.includes('runway') || q.includes('30 days') || q.includes('forecast')) {
    const forecast = calculateCashForecast(state.cashBalance, state.receivables, state.payables);
    const minCash = Math.min(...forecast.map(d => d.baseScenarioCash));
    answer = `Opening Book Cash: ₹${state.cashBalance.toLocaleString('en-IN')}. Projected 30-day low point is ₹${minCash.toLocaleString('en-IN')}. Cash runway is stable under base scenario.`;
    basis = '30-day dynamic liquidity projection incorporating receivables, scheduled payables, and recurring commitments.';
    sources.push('Cash Flow Engine');
  } else if (q.includes('gst') || q.includes('tax') || q.includes('liability')) {
    const eligibleItc = getEligibleItc(state.gstRows);
    const netPayable = Math.max(0, state.salesTaxOutput - eligibleItc);
    answer = `Gross Output Tax: ₹${state.salesTaxOutput.toLocaleString('en-IN')}. Eligible ITC in GSTR-2B: ₹${eligibleItc.toLocaleString('en-IN')}. Net Cash GST Liability: ₹${netPayable.toLocaleString('en-IN')}.`;
    basis = 'Statutory GST offset calculation: Max(0, Output GST - Eligible ITC in GSTR-2B).';
    sources.push('GSTR-1 Output Register', 'GSTR-2B Matched ITC');
  } else {
    answer = `For ${state.company.legalName}: Total open receivables stand at ₹${state.receivables.reduce((a, b) => a + b.amount, 0).toLocaleString('en-IN')} and open payables stand at ₹${state.payables.reduce((a, b) => a + b.amount, 0).toLocaleString('en-IN')}. Net cash balance is ₹${state.cashBalance.toLocaleString('en-IN')}.`;
    basis = 'Real-time double-entry trial balance ledger snapshot.';
  }

  return {
    answer,
    basis,
    sources,
    providerUsed: 'deterministic'
  };
}

